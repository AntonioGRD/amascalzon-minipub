// Mappatura automatica window.MENU_DATA per compatibilità totale
if (typeof window.AMASCALZON_MENU !== 'undefined') {
  window.MENU_DATA = [];
  window.AMASCALZON_MENU.forEach(function (cat) {
    if (Array.isArray(cat.items)) {
      cat.items.forEach(function (it) {
        var numPrice = parseFloat(String(it.price || '0').replace('€', '').replace(',', '.').trim()) || 0;
        var isSpina = (cat.category && cat.category.toLowerCase().includes('spina')) || false;
        window.MENU_DATA.push({
          id: it.id,
          category: cat.category,
          name: it.title || it.name,
          description: it.desc || it.description || '',
          price: numPrice,
          image: it.img || it.image || '',
          ingredients: it.ingredients || [],
          dineInOnly: isSpina
        });
      });
    }
  });
}
